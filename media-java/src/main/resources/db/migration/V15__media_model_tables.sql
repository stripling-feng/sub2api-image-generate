SELECT setval(
    pg_get_serial_sequence('media_model_providers', 'id'),
    COALESCE((SELECT MAX(id) FROM media_model_providers), 1),
    (SELECT COUNT(*) > 0 FROM media_model_providers)
);

SELECT setval(
    pg_get_serial_sequence('media_ai_models', 'id'),
    COALESCE((SELECT MAX(id) FROM media_ai_models), 1),
    (SELECT COUNT(*) > 0 FROM media_ai_models)
);

DO $$
DECLARE
    source_count bigint;
    target_count bigint;
BEGIN
    SELECT COUNT(*) INTO source_count FROM model_providers;
    SELECT COUNT(*) INTO target_count FROM media_model_providers;
    IF source_count <> target_count THEN
        RAISE EXCEPTION 'media_model_providers copy count mismatch: % <> %', source_count, target_count;
    END IF;

    SELECT COUNT(*) INTO source_count FROM ai_models;
    SELECT COUNT(*) INTO target_count FROM media_ai_models;
    IF source_count <> target_count THEN
        RAISE EXCEPTION 'media_ai_models copy count mismatch: % <> %', source_count, target_count;
    END IF;

    IF EXISTS (
        SELECT 1 FROM model_providers source
        LEFT JOIN media_model_providers target ON target.id = source.id
        WHERE target.id IS NULL
    ) THEN
        RAISE EXCEPTION 'media_model_providers primary key copy mismatch';
    END IF;

    IF EXISTS (
        SELECT 1 FROM ai_models source
        LEFT JOIN media_ai_models target ON target.id = source.id
        WHERE target.id IS NULL OR target.provider_id <> source.provider_id
    ) THEN
        RAISE EXCEPTION 'media_ai_models primary key or provider copy mismatch';
    END IF;

    IF EXISTS (
        SELECT 1 FROM media_ai_models model
        LEFT JOIN media_model_providers provider ON provider.id = model.provider_id
        WHERE provider.id IS NULL
    ) THEN
        RAISE EXCEPTION 'media_ai_models contains an orphan provider reference';
    END IF;
END $$;

