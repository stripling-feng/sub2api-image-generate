CREATE TABLE media_model_providers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    base_url text NOT NULL,
    image_api_key text NOT NULL DEFAULT '',
    video_api_key text NOT NULL DEFAULT '',
    enabled smallint NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
    provider_sort integer NOT NULL DEFAULT 0,
    create_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user_id bigint,
    update_user_id bigint,
    deleted smallint NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1))
);

CREATE TABLE media_ai_models (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id bigint NOT NULL REFERENCES media_model_providers(id),
    model_type text NOT NULL CHECK (model_type IN ('IMAGE', 'VIDEO')),
    model_key text NOT NULL UNIQUE,
    display_name text NOT NULL,
    upstream_model text NOT NULL,
    generation_path text NOT NULL,
    edit_path text,
    async_mode smallint NOT NULL DEFAULT 1 CHECK (async_mode IN (0, 1)),
    max_count integer NOT NULL DEFAULT 1 CHECK (max_count BETWEEN 1 AND 10),
    max_reference_images integer NOT NULL DEFAULT 0 CHECK (max_reference_images BETWEEN 0 AND 10),
    supports_mask smallint NOT NULL DEFAULT 0 CHECK (supports_mask IN (0, 1)),
    parameter_schema jsonb NOT NULL DEFAULT '[]'::jsonb,
    default_params jsonb NOT NULL DEFAULT '{}'::jsonb,
    enabled smallint NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
    model_sort integer NOT NULL DEFAULT 0,
    create_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_user_id bigint,
    update_user_id bigint,
    deleted smallint NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1)),
    unit_price_usd numeric(20,10) NOT NULL DEFAULT 0.5 CHECK (unit_price_usd >= 0),
    billing_mode varchar(20) NOT NULL DEFAULT 'PER_REQUEST'
        CHECK (billing_mode IN ('PER_REQUEST', 'PER_SECOND'))
);

CREATE INDEX media_ai_models_provider_id_idx ON media_ai_models(provider_id);
CREATE INDEX media_ai_models_type_enabled_idx
    ON media_ai_models(model_type, enabled, model_sort) WHERE deleted = 0;

